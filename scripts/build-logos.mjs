// Writes official brand marks (from the simple-icons set) into public/logos as SVGs,
// keeping each brand's own colour, and generates src/lib/logos.generated.ts with the hex values.
// Icon artwork: CC0 (simple-icons). Trademarks remain with their owners; see public/logos/LICENSE-*.
import * as si from "simple-icons";
import { writeFileSync, copyFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// data slug -> simple-icons export. Microsoft/Azure/AWS marks are not in simple-icons any more;
// those skills use line icons in TechLogo.tsx instead.
const BRANDS = {
  angular: "siAngular", react: "siReact", bootstrap: "siBootstrap", sass: "siSass",
  javascript: "siJavascript", typescript: "siTypescript", jquery: "siJquery",
  dotnet: "siDotnet", laravel: "siLaravel", springboot: "siSpringboot", php: "siPhp",
  mysql: "siMysql", postgresql: "siPostgresql",
  mongodb: "siMongodb", firebase: "siFirebase", 
   docker: "siDocker", kubernetes: "siKubernetes", python: "siPython",
  r: "siR", selenium: "siSelenium", linux: "siLinux", redis: "siRedis",
  elasticsearch: "siElasticsearch", git: "siGit", bitbucket: "siBitbucket",
  rabbitmq: "siRabbitmq", postman: "siPostman", swagger: "siSwagger",
  jmeter: "siApachejmeter", jwt: "siJsonwebtokens",
};

const out = {};
const missing = [];
for (const [slug, exportName] of Object.entries(BRANDS)) {
  const icon = si[exportName];
  if (!icon) { missing.push(`${slug} (${exportName})`); continue; }
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" role="img" aria-label="${icon.title}">` +
    `<path fill="#${icon.hex}" d="${icon.path}"/></svg>\n`;
  writeFileSync(join(root, "public/logos", `${slug}.svg`), svg);
  out[slug] = icon.hex;
}

copyFileSync(join(root, "node_modules/simple-icons/LICENSE.md"), join(root, "public/logos/LICENSE-simple-icons.md"));
copyFileSync(join(root, "node_modules/simple-icons/DISCLAIMER.md"), join(root, "public/logos/DISCLAIMER-simple-icons.md"));

writeFileSync(
  join(root, "src/lib/logos.generated.ts"),
  "// Generated by scripts/build-logos.mjs. Do not edit.\n" +
  `export const BRAND_HEX: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`,
);

console.log(`wrote ${Object.keys(out).length} brand logos`);
if (missing.length) console.warn("missing exports:", missing.join(", "));
